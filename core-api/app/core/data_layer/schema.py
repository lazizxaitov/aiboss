def _source_tracked_columns() -> tuple[SchemaColumn, ...]:
    """Return the common source-tracked columns for normalized SmartUp entities."""

    return (
        SchemaColumn("organization_id", "uuid"),
        SchemaColumn("source_system", "text", default="'smartup'"),
        SchemaColumn("source_external_id", "text"),
        SchemaColumn("source_filial_id", "text", nullable=True),
        SchemaColumn("source_payload_id", "text", nullable=True),
        SchemaColumn("source_created_at", "timestamptz", nullable=True),
        SchemaColumn("source_updated_at", "timestamptz", nullable=True),
        SchemaColumn("imported_at", "timestamptz"),
        SchemaColumn("last_synced_at", "timestamptz", nullable=True),
        SchemaColumn("metadata", "jsonb", default="{}"),
        *COMMON_AUDIT_COLUMNS,
    )


def _source_tracked_indexes(*extra_indexes: tuple[str, ...]) -> tuple[tuple[str, ...], ...]:
    """Return canonical indexes for source-tracked tables."""

    return (("organization_id", "source_system", "source_external_id"), *extra_indexes)


def _normalized_entity_table(
    *,
    name: str,
    description: str,
    primary_key: str,
    extra_columns: tuple[SchemaColumn, ...],
    indexes: tuple[tuple[str, ...], ...] = (),
) -> SchemaTable:
    """Create a source-tracked normalized entity table definition."""

    return SchemaTable(
        name=name,
        description=description,
        primary_key=primary_key,
        columns=(
            SchemaColumn(primary_key, "uuid", unique=True),
            *_source_tracked_columns(),
            *extra_columns,
        ),
        indexes=_source_tracked_indexes(*indexes),
    )


def _canonical_source_columns(
    *,
    include_organization_id: bool = True,
) -> tuple[SchemaColumn, ...]:
    """Return the common provenance columns for canonical V2 tables."""

    columns = [
        SchemaColumn("source_system", "text", default="'smartup'"),
        SchemaColumn("source_endpoint", "text"),
        SchemaColumn("source_external_id", "text"),
        SchemaColumn("source_raw_record_id", "uuid", nullable=True),
        SchemaColumn("request_filial_id", "text", nullable=True),
        SchemaColumn("response_filial_id", "text", nullable=True),
        SchemaColumn("request_company_id", "text", nullable=True),
        SchemaColumn("request_project_code", "text", nullable=True),
        SchemaColumn("source_raw_batch_id", "uuid", nullable=True),
        SchemaColumn("data_quality_status", "text"),
        SchemaColumn("imported_at", "timestamptz"),
        SchemaColumn("last_synced_at", "timestamptz", nullable=True),
        SchemaColumn("metadata", "jsonb", default="{}"),
        *COMMON_AUDIT_COLUMNS,
    ]
    if include_organization_id:
        return (SchemaColumn("organization_id", "uuid"), *columns)
    return tuple(columns)


def _canonical_entity_table(
    *,
    name: str,
    description: str,
    primary_key: str,
    extra_columns: tuple[SchemaColumn, ...],
    indexes: tuple[tuple[str, ...], ...] = (),
) -> SchemaTable:
    """Create a source-tracked canonical V2 table definition."""

    include_organization_id = primary_key != "organization_id"
    return SchemaTable(
        name=name,
        description=description,
        primary_key=primary_key,
        columns=(
            SchemaColumn(primary_key, "uuid", unique=True),
            *_canonical_source_columns(include_organization_id=include_organization_id),
            *extra_columns,
        ),
        indexes=_canonical_indexes(include_organization_id, *indexes),
    )


def _canonical_indexes(
    include_organization_id: bool,
    *extra_indexes: tuple[str, ...],
) -> tuple[tuple[str, ...], ...]:
    """Return canonical indexes for V2 tables."""

    base_index = ("organization_id", "source_system", "source_external_id")
    if not include_organization_id:
        base_index = ("source_system", "source_external_id")
    return (base_index, *extra_indexes)


